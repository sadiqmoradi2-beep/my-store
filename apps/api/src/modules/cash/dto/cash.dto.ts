import { Type } from 'class-transformer';
import { IsDateString, IsEnum, IsIn, IsNumber, IsOptional, IsString, Max, MaxLength, Min, MinLength, ValidateNested } from 'class-validator';
import { PaginationQueryDto } from '../../../common/dto/pagination-query.dto';

/** Sanity cap on a register transaction/balance — guards against a typo (extra digit) */
const MAX_CASH_AMOUNT = 10_000_000_000;

/** A person picked in Paid By / Who Is Paid: which table (kind) + the id in that table */
export class PersonSelectionDto {
  @IsIn(['EMPLOYEE', 'PARTNER', 'PERSON'])
  kind: 'EMPLOYEE' | 'PARTNER' | 'PERSON';

  @IsString()
  @MaxLength(64)
  @MinLength(1)
  id: string;
}

/** Staff attribution only. Selection is restricted to Store Admin; other logins resolve their own identity. */
export class PersonnelSelectionDto {
  @IsIn(['PAYMENT', 'RECEIVE', 'TRANSFER'])
  operation: 'PAYMENT' | 'RECEIVE' | 'TRANSFER';

  @IsString()
  @MaxLength(64)
  @MinLength(1)
  personId: string;
}

/** Manual entry of income/expense/withdrawal — SALE and REFUND are only recorded by the system */
export class CreateCashTransactionDto {
  @IsEnum(['INCOME', 'EXPENSE', 'WITHDRAWAL'])
  type: 'INCOME' | 'EXPENSE' | 'WITHDRAWAL';

  @Type(() => Number)
  @IsNumber({ maxDecimalPlaces: 2 })
  @Min(0.01)
  @Max(MAX_CASH_AMOUNT)
  amount: number;

  @IsOptional()
  @IsString()
  @MaxLength(80)
  category?: string;

  @IsOptional()
  @IsString()
  note?: string;

  /** Optional pay slip / receipt photo URL (from POST /uploads/cash-receipts) */
  @IsOptional()
  @IsString()
  receiptUrl?: string;

  /** The work session whose cash box paid / received this. Empty = the main cash box; not given = the user's own active session */
  @IsOptional()
  @IsString()
  sessionId?: string | null;

  /** When it happened — leave empty for now; a past date back-fills an old transaction (no future dates) */
  @IsOptional()
  @IsDateString()
  date?: string;

  /** External payer for income. Outgoing requests may use this as a validated legacy staff actor alias. */
  @IsOptional()
  @ValidateNested()
  @Type(() => PersonSelectionDto)
  paidBy?: PersonSelectionDto;

  /** Actual recipient for expenses/withdrawals. Incoming requests may use this as a validated legacy staff actor alias. */
  @IsOptional()
  @ValidateNested()
  @Type(() => PersonSelectionDto)
  receivedBy?: PersonSelectionDto;

  /** Optional staff actor on any account; RECEIVE for income, PAYMENT for expense/withdrawal. */
  @IsOptional()
  @ValidateNested()
  @Type(() => PersonnelSelectionDto)
  personnel?: PersonnelSelectionDto;

  /** Descriptive payment destination; never creates another money movement. */
  @IsOptional()
  @IsString()
  @MaxLength(200)
  destination?: string;
}

export class CashTransactionListQueryDto extends PaginationQueryDto {
  @IsOptional()
  @IsEnum(['SALE', 'INCOME', 'EXPENSE', 'REFUND', 'WITHDRAWAL', 'TRANSFER_IN', 'TRANSFER_OUT'])
  type?: 'SALE' | 'INCOME' | 'EXPENSE' | 'REFUND' | 'WITHDRAWAL' | 'TRANSFER_IN' | 'TRANSFER_OUT';

  /** e.g. "salary" or "partner" — filters to cash effects generated by that feature */
  @IsOptional()
  @IsString()
  referenceType?: string;
}

export class IncomeSummaryQueryDto {
  /** Range start — defaults to the first day of the current month */
  @IsOptional()
  @IsDateString()
  from?: string;

  /** Range end (whole day included) — defaults to now */
  @IsOptional()
  @IsDateString()
  to?: string;

  @IsOptional()
  @IsString()
  branchId?: string;
}
